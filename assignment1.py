# Assignment 1 - Represent everyday objects as data types

# Desk lamp -> Boolean
deskLamp = True

# Water bottle -> Number
waterBottle = 500  # ml

# Glasses -> Object / Dictionary
glasses = {
    "color": "silver",
    "frame": "metal",
    "lens": "clear"
}

# Keys -> Array / List
keys = ["apartment key", "mailbox key", "lobby key"]

print("Desk lamp:", deskLamp)
print("Water bottle:", waterBottle)
print("Glasses:", glasses)
print("Keys:", keys)